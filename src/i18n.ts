let table: Record<string, string> | null = null;

export function initI18n(pref: "auto" | "en" | "ru") {
  const lang = pref === "auto" ? (navigator.language || "en").toLowerCase() : pref;
  const isRu = lang.startsWith("ru");
  table = isRu ? ru : null;
  setLocaleName(isRu ? "ru" : (pref === "auto" ? navigator.language || "en" : "en"));
  document.documentElement.lang = isRu ? "ru" : "en";
}

export function t(s: string, ...args: (string | number)[]): string {
  let r = table?.[s] ?? s;
  if (args.length) r = r.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ""));
  return r;
}
